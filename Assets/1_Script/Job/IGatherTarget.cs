using UnityEngine;

// **"저건 가져와라"라고 찍을 수 있는 것**(2026-09-06).
//
// 사용자: *"버섯을 처음에 자동채집이 켜져있으면 안돼 내가 시켜야지 마치 운반을 시키는
// 것처럼."* — 그 *"운반을 시키는 것처럼"*이 이 인터페이스다.
//
// ## 모드를 새로 만들지 않는다
//
// 채집 지정 모드를 따로 내면 **같은 손놀림을 두 번 배우게 된다**(드래그로 네모를 치고
// 우클릭으로 무른다 — 조작이 한 글자도 안 다르다). 그리고 모드가 하나 늘 때마다
// `ExclusiveMode`의 식구가 늘고, 모드 바가 한 칸 늘고, 단축키가 하나 더 든다.
//
// **바닥의 물건과 채집물은 플레이어에게 같은 것이다** — *저기 있는 가져올 것*. 그래서
// `HaulDesignator` 하나가 둘 다 찍는다. 갈리는 것은 **찍힌 뒤에 무슨 일감이 나가느냐**뿐이고,
// 그건 각자가 안다(`DroppedItem`은 운반, `Forageable`은 채집).
//
// ## 기본은 꺼짐이다
//
// **`DroppedItem`이 이미 그 규칙이다**(*"바닥의 물건은 아무도 안 건드린다 — 체크한 것만
// 실려 간다"*). 채집물만 저 혼자 켜져 있으면 **같은 화면의 같은 조작이 물건마다 다르게
// 돈다.** 설비가 내놓는 것(캔 돌 · 작물 · 작업대 산출)은 이 축과 무관하게 그대로 자동이다 —
// 그건 전리품이 아니라 **생산물**이고, 바닥을 거치는 것은 구현 사정일 뿐이다.
public interface IGatherTarget
{
    // 찍혔나.
    bool Designated { get; }

    // **찍을 수 있나**(2026-09-06). 같은 타입인데 개체에 따라 갈리는 것이 생겼다 —
    // 자원 노드는 **야생만** 찍히고 **지은 것은 배정**이다. 이 물음이 없으면 지정 모드가
    // 지은 광맥에도 예정 표식을 띄우고, 눌러도 아무 일이 안 일어난다(**찍히는 것처럼 보이는데
    // 안 찍힌다**가 가장 나쁘다).
    bool CanDesignate => true;

    // 찍는다 / 무른다. **여기서 일감이 나가고 거둬진다** — 부르는 쪽(모드)은 그걸 모른다.
    void SetDesignated(bool on);

    // 드래그하는 동안의 예정 표시. **결과와 같은 모양을 흐리게** 띄운다 —
    // 미리보기와 결과가 다르면 무엇이 될지 알 수 없다.
    void SetPendingHighlight(bool on);

    // 화면 좌표로 옮겨 네모 안인지 재는 쪽이 쓴다.
    Transform Where { get; }
}
