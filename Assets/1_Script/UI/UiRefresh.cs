using UnityEngine;

// **화면이 다시 그려지는 박자 — 답은 여기 하나다**(2026-09-23, 사용자: *"각자 지연을 두면 깔끔하지
// 않으니깐 한 곳에서 관리하는게 어떠냐"*).
//
// 그전에는 창 여덟이 저마다 `refreshInterval`과 제 타이머를 들었다. 창이 떨어져 있으면 몇 프레임
// 어긋나도 아무도 모르지만, **붙어 선 두 판**(`PawnSheet_Panel` ↔ `PawnHealth_Panel`)에서는 그것이
// 곧 **한 창이 두 번에 나눠 바뀌는 것**으로 보였다. 창마다 시계를 들면 언젠가 반드시 갈린다.
//
// ## 이 방식이 고치는 것 둘
//
//  · **같은 순간에 바뀐다** — 박이 세계에 하나라 0.15초 창과 0.3초 창이 **같은 프레임**에 돈다
//    (배수로 세기 때문에 느린 창이 갱신되는 순간은 언제나 빠른 창도 갱신되는 순간이다).
//    주기를 각자 들면 0.15와 0.3이 서로 나눠떨어져도 **시작 시각이 달라** 영영 안 맞는다.
//  · **멈춰도 돈다** — `Time.unscaledTime` 하나로 잰다. `GameTimeManager`가 `timeScale`을 만지므로
//    `deltaTime`으로 재던 창(무리 목록 · 거점 창)은 **일시정지 중에 값이 얼어붙었다** — 멈춰 세우는
//    이유의 절반이 들여다보려는 것이라 그건 그냥 안 되는 것과 같다(`UiTween`이 `SetUpdate(true)`로,
//    `CameraController`가 `Dt`로 피한 그 사고다).
//
// ## 어기면 조용히 깨지는 것
//
//  · **켜고 끄는 것을 이 박자에 태우지 말 것.** 여기가 답하는 것은 *언제 다시 그리나*이지
//    *보이나 안 보이나*가 아니다. 가시성을 주기에 태우면 모드를 끄고 한 박이 지나서야 판이
//    돌아오고, 그 지연은 **다른 박자로 도는 판과 어긋난 순간**으로 화면에 드러난다.
//  · **드라이버가 없다** — `Beat`는 `unscaledTime`에서 바로 나오는 순수한 값이다. 누가 매 프레임
//    올려 주는 식으로 두면 그 오브젝트가 없는 씬에서 화면이 통째로 멎는다.
//  · **배수는 코드가 적는다**(씬이 아니다) — 창마다 인스펙터에 주기를 두면 한 창만 어긋난 값으로
//    굳고, 그게 바로 걷어낸 상태다. 갱신 주기는 *저작*이 아니라 **규격**이다.
//  · **마우스를 따라가는 것은 여기 안 태운다** — 올린 칸의 설명(`PawnStoryText.Tick`)은 박을
//    안 기다린다(커서는 0.15초를 기다려 주지 않는다).
public static class UiRefresh
{
    // **한 박.** 창이 보여 주는 값 중 프레임 단위로 움직이는 것은 하나도 없다(가장 빠른 혈액이
    // 초당 몇이다). 더 내리면 큰 문자열을 짓는 값만 늘고, 더 올리면 숫자가 **뚝뚝 끊겨** 보인다.
    public const float Interval = 0.15f;

    // 0.15초마다 하나씩 오른다. **`unscaledTime` 하나에서 나온다** — 세계에 시계가 하나뿐이라
    // 모든 창이 같은 박에 떨어진다.
    public static int Beat => (int)(Time.unscaledTime / Interval);

    // **지금 다시 그릴 때인가.** `every`는 박의 배수다(1 = 0.15초 · 2 = 0.3초 · 4 = 0.6초).
    //
    //     int _beat = -1;   …   if (!UiRefresh.Due(ref _beat, 2)) return;
    //
    // **`last`를 −1로 시작할 것** — 0으로 두면 판이 열린 **첫 박**(게임 시작 직후)만 건너뛰어,
    // 그 한 번만 창이 비어 보인다.
    public static bool Due(ref int last, int every = 1)
    {
        int now = Beat / Mathf.Max(1, every);
        if (now == last) return false;
        last = now;
        return true;
    }

    // **지금 곧바로 한 번 그린다** — 다음 박을 안 기다린다. 모드가 갈리거나 고른 것이 바뀌는 것처럼
    // **사람이 방금 한 일**의 결과는 기다리면 안 된다(그 지연이 곧 *"눌렀는데 반응이 없다"*이다).
    public static void Now(ref int last) => last = -1;
}
