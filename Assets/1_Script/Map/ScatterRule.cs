using System;
using UnityEngine;

// **자잘한 것은 좌표에서 계산해 뿌린다** — 나무·바위(2026-08-26).
//
// 29,440m 세계에 나무를 손으로 놓을 수는 없다. 그래서 **좌표 해시로 결정적으로** 뿌린다 —
// 떠났다 돌아와도 **같은 자리에 같은 나무**가 선다(저장하는 것이 없다).
//
// **조건은 지형이 답한다** — 절벽에 나무가 서면 안 되고, 설선 위에도 없어야 한다.
// 그 판정은 `TerrainHeight`가 하므로 **청크가 로드 안 돼 있어도 계산된다.**
[Serializable]
public class ScatterRule
{
    public string Name = "나무";

    [Tooltip("`ResourceNode`가 붙은 프리팹(`3_Prefab/Node/`).")]
    public GameObject Prefab;

    [Tooltip("청크(256m) 하나당 몇 개. 소수도 된다 — 0.5면 두 청크에 하나꼴.")]
    [Min(0f)] public float PerChunk = 20f;

    [Header("설 수 있는 자리")]
    [Tooltip("경사(도). 나무는 완만한 데만 — 절벽에 서면 떠 보인다.")]
    public float MaxSlope = 25f;

    [Tooltip("고도(m). 설선 위에는 나무가 없다.")]
    public float MinHeight = -100f;
    public float MaxHeight =  400f;

    [Header("생김새")]
    public Vector2 ScaleRange = new(0.85f, 1.2f);

    [Tooltip("서로 이만큼(m)보다 가까우면 하나를 버린다. 0이면 안 본다.")]
    [Min(0f)] public float MinSpacing = 4f;

    [Header("지하")]
    // **바위 속에 세우지 않는다**(2026-09-06).
    //
    // 경사·고도만 보던 규칙은 **지상 것**이다. 지하로 온 뒤 세계의 상당 부분이 바위인데
    // 뿌리는 쪽이 그걸 한 번도 안 물었다 — 버섯을 그대로 뿌리면 **벽 속에서 자라고**,
    // 보이지도 갈 수도 없다. `CLAUDE.md`의 *"밖에서 온 것이 설 자리"*가 이 자리다
    // (마을이 벽 속에 서고, 무리가 벽에 끼고, 상인이 벽에서 튀어나오던 그 사고).
    //
    // **답은 `MapManager.IsWorkable` 하나다** — 통행 가능 + 설 수 있음(바위·머리 여유
    // 포함). 여기서 `RockMap`과 여유를 따로 조합하면 답이 두 벌이 된다.
    [Tooltip("걸을 수 있는 칸에만 세운다. 지하에서 뿌리는 것은 반드시 켤 것 — " +
             "끄면 바위 속에서 자란다.")]
    public bool RequireOpenTile = false;

    // **딴 것은 다시 자란다**(2026-09-06). 나무·바위는 0(안 자란다) — 벤 숲이 하룻밤에
    // 돌아오면 벌목이 뜻을 잃는다. **버섯은 다르다**: 그게 채집을 *되풀이되는 수입*으로
    // 만드는 축이고, 안 자라면 굴을 한 바퀴 돌고 나서 그 축이 통째로 끝난다.
    //
    // **자리는 안 기억한다** — 뿌리기가 결정적이므로 *잊기만 하면* 같은 자리에 다시 선다.
    [Tooltip("딴 뒤 며칠 만에 다시 나나. 0이면 다시 안 난다(나무·바위).")]
    [Min(0f)] public float RegrowDays = 0f;

    // **어느 바이옴에 나나** — 비우면 전부(나무·바위는 그렇게 둔다).
    //
    // **`BiomeContentData.ResourceNodes`는 이 물음의 답이 아니다**(2026-09-06에 한 번
    // 틀렸다). 그쪽은 **바위 속 광맥 풀**이다 — *"이 바이옴의 벽을 파면 무엇이 나오나"*.
    // 거기 버섯을 넣으면 **버섯이 광맥으로 나온다**(바닥에 나야 할 것이 벽 속에 박힌다).
    // *"이 바이옴 바닥에 무엇이 나나"*는 물음이 다르고, 답할 자리가 여기까지 없었다.
    [Tooltip("이 바이옴에서만 뿌린다. 비우면 어디에나.")]
    public Biome[] Biomes = System.Array.Empty<Biome>();

    [Header("무리")]
    // **채집물은 한 자리에 여럿이 난다**(2026-09-06, 사용자: *"버섯같은거는 채집물이니깐
    // 하나씩 나오는게 아니라 한번에 근처에서 3~4개가 같이 나와도 될 거 같아(내용물이 아니라
    // 실제 배치가)"*).
    //
    // **프리팹에 갓을 더 그리는 것과 다른 물음이다** — 그건 *물건 하나가 어떻게 생겼나*이고,
    // 이건 *물건이 몇 개 있나*다. 채집은 **하나씩 딴다**: 한 자리에서 서넛이 나야 폰이 거기
    // 서서 몇 번을 따고, 그것이 *"버섯밭을 만났다"*로 읽힌다. 갓만 늘리면 여전히 **한 번
    // 따면 무리째 사라진다.**
    //
    // 나무·바위는 1이라 **예전과 한 톨도 안 달라진다.**
    [Tooltip("한 자리에 몇 개가 같이 나나. 1이면 하나씩(나무·바위).")]
    [Min(1)] public int ClusterMin = 1;
    [Min(1)] public int ClusterMax = 1;

    // **칸으로 잰다 — 미터가 아니다**(2026-09-06, 사용자: *"갓버섯끼리 떨어져서 태어나잖아
    // 내가 원하는건 바로옆칸에 따닥따닥붙어있는 배치야"*).
    //
    // 처음에는 반경 2.5m 원 안에 **무작위로 흩뿌렸다.** 그러면 서넛이 *같은 동네*에 서기는
    // 하는데 **서로 떨어져 선다** — 원 안의 점을 고르는 일에는 *"붙어 있어라"*라고 적을
    // 자리가 없다. 반경을 줄이면 이번엔 **한 점에 겹친다.**
    //
    // 그래서 자리를 **맞닿은 칸에서 고른다.** 1이면 제 칸과 이웃 여덟, 2면 그 바깥까지.
    // 칸이 1m라 **칸을 고르는 순간 간격이 정확히 1m로 정해지고**, 겹치지도 벌어지지도
    // 않는다 — *따닥따닥*이 규칙에서 나온다.
    [Tooltip("무리가 퍼지는 범위(칸). 1이면 제 칸 + 맞닿은 여덟 칸.")]
    [Min(0)] public int ClusterSpread = 1;
}
