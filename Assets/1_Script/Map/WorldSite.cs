using System;
using UnityEngine;

// **저작한 장소** — 마을 · 주둔지 · 유적(2026-08-26).
//
// **프리팹을 손으로 짓는 방식은 안 바뀐다.** 씬에서 하던 대로 울타리·막사·폰을 배치해
// 하나로 묶고 프리팹으로 저장한 다음, **여기에 좌표 한 줄**을 적는다. 달라지는 것은
// *"씬에 놓는다"*가 *"프리팹 + 좌표"*가 되는 것뿐이고, 덤으로 마을 하나를 통째로 복사해
// 다른 데 놓기가 쉬워진다.
//
// 29km 세계의 프리팹을 씬 하나에 다 둘 수 없어서 이렇게 간다 — 가까이 가면 서고 멀어지면
// 사라진다(지형 청크와 같은 스트리밍).
[Serializable]
public class WorldSite
{
    public string Name = "장소";
    public GameObject Prefab;

    [Tooltip("월드 좌표(m). 세계는 0 ~ 29,440.")]
    public Vector2 Position;

    [Tooltip("지면에서 띄울 높이(m). 0이면 지면에 딱 붙는다.")]
    public float YOffset;

    [Range(0f, 360f)] public float Rotation;

    // **한 번 서면 안 내린다** — 마을처럼 **상태를 들고 있는** 장소가 그렇다. 내렸다 다시
    // 세우면 그 안의 창고·폰·건물이 처음으로 돌아간다(그 상태를 스냅샷으로 들고 내리는 것은
    // 7번 "시뮬 지역성"의 일이다). 바위 무더기 같은 장식은 꺼 두면 메모리를 아낀다.
    [Tooltip("켜면 한 번 뜬 뒤로는 안 사라진다. 마을처럼 상태를 들고 있는 곳에.")]
    public bool Persistent = true;

    // **손으로 놓은 것인가, 도구가 지도에서 뽑은 것인가**(2026-08-26).
    //
    // `5. Place Sites From World Map`은 목록을 통째로 다시 쓴다 — 지도가 답이므로 그게 맞다.
    // 그런데 **손으로 지어 놓은 도시가 그때 같이 지워지면** 다시 돌릴 엄두가 안 난다.
    // 그래서 도구는 **`FromMap`인 것만** 건드리고 손으로 놓은 것은 지나간다.
    [Tooltip("도구가 지도에서 뽑은 것. 끄면 손으로 놓은 것이라 도구가 안 건드린다.")]
    public bool FromMap;
}
