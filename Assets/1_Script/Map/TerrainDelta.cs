using UnityEngine;

// **손댄 정점만 담는다** — 청크 하나 몫.
//
// 세계 전체 높이맵은 축당 14,721 정점 = **2억 1,700만 개**(16비트로도 433MB)라 저장할 수
// 없다. 그래서 원본은 **노이즈 함수**이고, 저작으로 바꾼 자리만 여기 남는다.
// **안 건드린 청크는 에셋 자체가 없다.**
//
// ── 소유권: 가장자리 정점은 누구 것인가 ─────────────────────────────────────
//
// 청크는 129×129 정점으로 그려지는데 **마지막 줄은 이웃 청크의 첫 줄과 같은 자리**다
// (`TerrainGrid.VertsPerAxis` = 128 + 1). 그 줄을 두 청크가 각자 저장하면 **한쪽만 손댔을 때
// 값이 갈려 이음매에 틈이 생긴다.**
//
// 그래서 **전역 정점 좌표로 주인을 정한다**: 전역 정점 `g`의 주인은 `g / 128` 청크이고
// 그 안에서 `g % 128`이다. 즉 **한 청크가 소유하는 것은 0~127 줄뿐**이고, 128번째 줄은
// 언제나 **이웃의 0번 줄**이다(세계 맨 끝만 예외로 마지막 청크가 128까지 갖는다).
// 그리는 쪽은 이웃 셋의 델타를 같이 물어보면 된다 — 값이 갈릴 자리가 **구조적으로 없다.**
public class TerrainDelta : ScriptableObject
{
    public Vector2Int Chunk;

    // 소유 정점의 지역 인덱스(`vz * TerrainGrid.VertsPerAxis + vx`)와 그 높이(m, 절대값).
    // **두 배열을 나란히 두는 것이 `Dictionary`를 직렬화하는 것보다 싸다** — 유니티가 사전을
    // 직렬화하지 않고, 청크당 수만 개가 들어갈 수 있는 자리다.
    public int[]   Index = System.Array.Empty<int>();
    public float[] Height = System.Array.Empty<float>();
}
