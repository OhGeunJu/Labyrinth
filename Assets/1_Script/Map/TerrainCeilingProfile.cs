using System;
using UnityEngine;

// 천장의 성격 — 노이즈 파라미터 한 벌. `TerrainProfile`의 짝이다.
//
// ── 왜 절대 높이가 아니라 "여유"인가 ────────────────────────────────────────
//
// 천장을 바닥과 무관한 절대 높이 함수로 두면, 둘이 제멋대로 오르내려 **어디가 방이고 어디가
// 바위인지를 저작할 수가 없다** — 산 위에서는 천장이 땅에 파묻히고 골짜기에서는 200m 위에
// 떠 있다. 값 하나를 보고 *"여기 지나갈 수 있나"*를 답할 수 없다는 뜻이다.
//
// **여유(clearance = 천장 − 바닥)로 두면 그 값 하나가 곧 답이다:**
//
//     여유 ≤ 0        바위다 (천장이 바닥을 만난다)
//     0 < 여유 < 폰 키  기어야 지날 틈 — **길찾기가 막아야 하는 자리**
//     여유 ≥ 폰 키     지나갈 수 있는 굴
//
// 그리고 딸려 오는 것이 하나 더 있다: **바닥을 다시 구워도 천장이 안 어긋난다.** 절대
// 높이로 저장하면 지형을 다시 굽는 순간 천장이 통째로 제자리에 남아 땅에 파묻히거나
// 하늘로 뜬다 — `WorldObject`가 높이를 저장하지 않는 것(XZ + `YOffset`)과 같은 이유다.
//
// ── 열림은 점이 아니라 선이다 (2026-08-30에 갈아엎었다) ────────────────────
//
// 처음에는 여유를 **노이즈의 합**으로 냈다(`기준 + 동굴 ± 통로 ± 요철`). 그러면 열리는
// 자리가 **여러 노이즈가 동시에 꼭대기에 오는 곳**이라, 굴이 *점점이 뜬 물방울*로 생기고
// **길이 안 난다** — 실제로 화면에는 시작 공터 하나만 둥그렇게 있었다. 진폭을 키우면
// 물방울이 커질 뿐 이어지지는 않는다(*"동굴처럼 길이 나 있으면 좋겠다"* — 사용자).
//
// **길이 나려면 열림이 곡선이어야 한다.** 그래서 축을 뒤집었다:
//
//     여유 = Lerp(바위, 굴, 열림)          열림 = max(간선, 잔가지, 방)
//
// **열림은 능선(ridge)이 만든다** — 노이즈의 **등고선**(값이 0인 자리)은 세계를 가로지르는
// 긴 곡선이고, 그 곡선에서 일정 거리 안쪽을 열면 그것이 곧 **구불구불한 통로**다. 두 벌을
// 다른 주기로 겹치면 서로 교차해 **그물**이 된다 — 막다른 길과 갈림길이 저절로 생긴다.
//
// **더하지 않고 max를 쓴다.** 더하면 통로와 방이 **겹치는 자리만** 문턱을 넘어서 길이 다시
// 토막 난다(합의 함정으로 되돌아간다). max는 *"둘 중 하나만 열려 있어도 열렸다"*이고,
// 그래야 방이 통로에 **매달린다**.
[Serializable]
public struct TerrainCeilingProfile
{
    [Tooltip("같은 시드면 언제 어디서 계산해도 같은 천장이 나온다 — 청크 경계가 안 갈라지는 근거다.")]
    public int Seed;

    [Header("바위와 굴 — 두 끝값")]
    [Tooltip("안 뚫린 자리의 여유(m). **음수여야 한다** — 0이면 천장이 지면에 붙어 z-파이팅이 " +
             "나고, 양수면 세계가 통째로 뚫린다. 이 값이 깊을수록 벽이 두껍게 읽힌다.")]
    public float BaseClearance;

    [Tooltip("뚫린 굴의 여유(m) = **굴 천장 높이**. 폰 키(1.8m)보다 넉넉해야 한다.")]
    public float OpenClearance;

    [Header("길 — 능선을 따라 난 통로 (간선)")]
    [Tooltip("굴곡의 크기(m). 클수록 길게 뻗고 작을수록 자주 꺾인다. **세계 한 변보다 " +
             "크면 세계에 길이 한 줄만 지나간다** — 세계가 256m면 100m 언저리.")]
    public float PassagePeriod;

    [Tooltip("통로 폭(m). **미터로 적는다** — 노이즈 문턱으로 적으면 주기를 바꿀 때마다 폭이 " +
             "같이 변해서 저작이 짐작이 된다(능선까지의 거리를 기울기로 재는 이유).")]
    public float PassageWidth;

    [Header("길 — 잔가지 (간선과 교차해 그물이 된다)")]
    public float BranchPeriod;
    public float BranchWidth;

    [Header("방 — 통로가 넓어지는 자리")]
    public float ChamberPeriod;

    [Tooltip("0~1. **높을수록 드물다.** 0.5면 절반이 방이 되어 굴이 아니라 들판이 된다.")]
    [Range(0f, 1f)] public float ChamberRarity;

    [Header("요철 — 천장의 울퉁불퉁함")]
    public float RoughPeriod;

    [Tooltip("**뚫린 자리에서만 얹는다.** 벽에까지 얹으면 문턱 바로 옆에서 흔들려 " +
             "**칸 하나씩 뚫렸다 막혔다** 하는 톱니 벽이 된다.")]
    public float RoughAmplitude;

    [Tooltip("바위가 바닥 **아래로** 얼마나 파묻히게 그릴 것인가(m). 0이면 천장 면과 지면이 " +
             "정확히 같은 높이에서 만나 **z-파이팅**이 난다 — 조금 파묻어야 바위가 땅에서 " +
             "솟은 것처럼 보인다. **판정에는 안 쓴다**(그리기 전용).")]
    public float SinkDepth;

    // ── 기본값의 근거 ───────────────────────────────────────────────────────
    //
    // **세계가 256m라는 것이 이 값들의 전제다.** 간선 주기 100m면 세계를 두어 번 가로지르는
    // 길이 나고, 잔가지 42m가 그것을 잘게 이어 그물이 된다. 세계를 넓히면 주기도 같이
    // 키울 것 — 안 그러면 길이 실뭉치처럼 빽빽해져 **바위가 남지 않는다.**
    //
    // **열린 넓이는 실측 24%다**(2026-08-30에 쟀다 — 함수 그대로 25.1% · 2m 정점 격자로
    // 보간해도 24.1%로 거의 같다). 처음 주석에 "3분의 1 언저리"라고 적었던 것은 어림이었다.
    // 나머지 4분의 3이 캘 바위다 — **다 뚫려 있으면 캐면서 넓힌다는 루프가 없다.**
    //
    // **더 트이게 하는 손잡이는 폭이다**(재 둔 값: 12/7/0.62 → 37% · 14/9/0.58 → 49% ·
    // 16/11/0.55 → 60%). 다만 **화면의 인상은 넓이보다 벽 높이가 더 정한다** — 9.6m 벽은
    // 비스듬한 카메라에서 뒤쪽 바닥을 통째로 가리므로, 넓이를 키우는 것보다 `RockMap.Height`를
    // 내리는 쪽이 훨씬 트여 보인다(그쪽은 **판정을 한 줄도 안 바꾼다**).
    public static TerrainCeilingProfile Default => new()
    {
        Seed            = 20260829,

        BaseClearance   = -11f,
        OpenClearance   = 6f,

        PassagePeriod   = 100f,
        PassageWidth    = 9f,

        BranchPeriod    = 42f,
        BranchWidth     = 5f,

        ChamberPeriod   = 70f,
        ChamberRarity   = 0.66f,

        RoughPeriod     = 18f,
        RoughAmplitude  = 0.6f,

        SinkDepth       = 2f,
    };
}
