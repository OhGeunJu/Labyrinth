using UnityEngine;

[CreateAssetMenu(menuName = "DungeonColony/ResourceNodeData")]
public class ResourceNodeData : ScriptableObject
{
    [Tooltip("이 노드가 내놓는 자원 아이템. **이것이 노드의 정체성이다** — " +
             "예전엔 ResourceType enum이 옆에 같이 있었는데, 이 필드와 늘 같은 것을 가리켜서 지웠다.")]
    public ItemData DropItem;

    // 목재 묶음을 내놓는 노드 = 나무. 채굴이 아니라 **벌목**이고, UI 문구도 스킬도 갈린다.
    // 예전엔 `ResourceType == Wood`로 봤는데, 그러면 모드가 넣은 나무는 영영 벌목이 안 된다.
    // 묶음으로 보면 `"resourceGroup": "Wood"` 자원을 내놓는 것은 무엇이든 나무로 취급된다.
    public bool IsTree => DropItem is ResourceItemData r && r.Group == ResourceGroup.Wood;


    // **이름과 설명은 저작한다 — 비우면 예전처럼 파생시킨다**(2026-09-06).
    //
    // 그전에는 살펴보기 창의 이름이 `{나오는 것} {나무|광맥}`이었다. 광맥에는 그게 맞는다
    // (*"철 광맥"*) — 그런데 **나오는 것이 정체가 아닌 물건**에는 안 맞는다: 거대버섯이
    // 목재를 내놓는다고 *"목재 나무"*라고 부를 수는 없다.
    //
    // **비워 두면 아무것도 안 바뀐다** — 지금 있는 노드 스물몇 개를 손대지 않으려는 것이다.
    [Tooltip("살펴보기 창에 뜰 이름. 비우면 `{나오는 것} 광맥/나무`로 짓는다.")]
    public string DisplayName;

    [Tooltip("살펴보기 창의 한 줄 설명. 비우면 안 뜬다.")]
    [TextArea(2, 4)] public string Description;

    [Tooltip("배치 시 사용할 프리팹. 비어있으면 BuildModeManager의 기본 프리팹 사용")]
    public GameObject Prefab;

    // 단위는 **스킬-초**(스킬 수치 × 작업한 초). 스킬 10인 폰이 15초 붙어 있으면 150.
    // 그래서 "초보(스킬 10) 기준 몇 초에 한 번 나오는가 × 10"으로 읽으면 된다.
    [Tooltip("1회 산출까지 필요한 작업량 (스킬-초 = 스킬 수치 × 작업 초). 스킬 10이 15초 → 150")]
    public float GaugeRequired = 100f;

    [Tooltip("게이지 1회 달성 시 드롭 수량 범위")]
    public int DropMin = 1;
    public int DropMax = 3;

    [Tooltip("이 자원 채굴의 권장 스킬 레벨 (XP 도전 비율 계산용)")]
    public float RequiredSkill = 0f;

    [Tooltip("이 노드에 동시에 붙을 수 있는 폰 수. 0이면 제한 없음. " +
             "노드가 차지하는 칸 수를 기준으로 잡으면 화면과 맞는다 (1×1은 1~2, 2×2는 3~4).")]
    [Min(0)] public int MaxWorkers = 2;

    // **몇 번 내놓고 없어지나**(2026-09-06, 사용자 결정: *"밖에있는 버섯나무도 그냥 어느정도
    // 캐다가 사라지는 걸로"*). 0이면 안 없어진다.
    //
    // **자연에 있는 것은 유한하고 지은 것은 무한하다** — 그 축이 이 게임의 자원 규칙이다:
    // 굴에서 캐 온 것으로 기지에 광맥을 이식하고(`Node_*Vein` 건물), 그때부터 그것이
    // 계속 내놓는다. 야생이 무한하면 **이식할 이유가 없고**, 이식이 유한하면 기지가
    // 늘 이사를 다녀야 한다.
    //
    // **여기 적는 것은 야생 쪽 눈금이다** — 지은 노드는 이 값을 안 본다(`ResourceNode.IsBuilt`).
    [Tooltip("몇 번 산출하고 없어지나. 0이면 안 없어진다. **지은 노드는 이 값을 안 본다.**")]
    [Min(0)] public int TotalYields = 0;

    // **숙성 축은 걷어냈다**(2026-09-06). 밭과 같은 모양으로 *"전력으로 익고 폰이 캔다"*를
    // 넣어 봤는데, 써 보니 **억지로 시간을 늘린 것**으로 읽혔다(사용자: *"돌이 자라는 시간은
    // 필요 없는 거 같아 그냥 억지로 시간늘리기 같은 느낌"*).
    //
    // 그 축이 뭘 하려던 것인지는 **전력이 이미 하고 있다** — 광맥을 몇 개나 돌릴 수 있나가
    // 값이고, 거기에 *기다리는 시간*을 하나 더 얹으면 **값이 두 벌이 되면서 둘 다 흐려진다.**
    // 캐는 속도는 채굴 스탯이 정하면 그만이다.
    //
    // **안 쓰는 손잡이는 남기지 않는다** — 남기면 다음에 읽는 사람이 *"이건 왜 0이지"*를 잰다.
}
