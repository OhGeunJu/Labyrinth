using UnityEngine;

// **손에 드는 것**(도구·무기) 프리팹에 붙는다. `PawnProps`가 손 뼈 아래에 세울 때 이 값으로 쥔다.
//
// ── 한 손 ──────────────────────────────────────────────────────────────────
// 쥐는 자리는 **손 뼈 기준**이다. 우리 두발 관절의 손(`HandR`)은 T자 자세에서 로컬 -Y가 손가락
// 쪽(팔을 따라 바깥), +Z가 앞(엄지 쪽)이다. 주먹을 쥐면 자루는 엄지에서 새끼손가락으로 —
// 손바닥을 가로질러 **Z**로 놓이고 머리는 엄지 쪽(+Z)이다. 팩의 도구 모델은 자루가 +Y로 서
// 있으므로 X로 90도 돌려 +Y를 +Z에 맞춘다 — 그것이 `GripEuler`의 기본값이다. **날의 방향은
// 눈으로 맞춘다** — 프리팹 인스펙터에서 이 값을 돌리면 그 도구를 든 모든 폰이 따라온다.
//
// ── 두 손 ──────────────────────────────────────────────────────────────────
// 곡괭이·도끼는 클립이 **두 손으로** 쥔다. 한 손에 고정하면 다른 손은 허공을 쥐고, 자루가
// 애니메이션과 따로 논다(*"땅바닥과 대칭으로 누워 있다"*). 그래서 두 손 도구는 고정하지 않고
// **매 프레임 양손 위치에서 자루 방향을 낸다**(`PawnProps.LateUpdate`): 자루는 왼손에서 오른손을
// 지나 머리로 이어지고(`HeadAxis`가 그쪽), 날은 몸에서 먼 쪽을 향한다(`EdgeAxis`). 클립이
// 내리찍으면 양손이 내려가므로 곡괭이도 같이 내려간다 — 자세를 따로 적을 것이 없다.
public class HandProp : MonoBehaviour
{
    [Tooltip("손 뼈에서 얼마나 비켜 쥐나(한 손: 손 뼈 로컬 / 두 손: 도구 로컬 — 자루를 따라 밀어 " +
             "손이 자루 한가운데를 쥐게 한다).")]
    public Vector3 GripOffset;

    [Tooltip("한 손 도구의 손 뼈 기준 회전(도). 기본 (90,0,0) = 모델의 +Y(자루)를 손의 +Z(엄지 쪽)에 맞춘다.")]
    public Vector3 GripEuler = new(90f, 0f, 0f);

    [Tooltip("왼손에 든다(방패).")]
    public bool LeftHand;

    [Header("두 손")]
    [Tooltip("양손으로 쥔다 — 자루 방향을 매 프레임 양손에서 낸다(곡괭이·도끼).")]
    public bool TwoHanded;

    [Tooltip("모델에서 자루가 머리 쪽으로 뻗는 축. 팩 도구는 +Y.")]
    public Vector3 HeadAxis = new(0f, 1f, 0f);

    [Tooltip("모델에서 날·촉이 튀어나온 축. 몸에서 먼 쪽을 향하게 돌린다. 틀리면 (1,0,0)으로.")]
    public Vector3 EdgeAxis = new(0f, 0f, 1f);
}
