public enum NpcType
{
    Villager,       // 배회 + 도망
    Guard,          // 순찰 + 전투
    ShopMerchant,   // 고정 (상점)
    EventMerchant,  // 걸어서 등장 → 대기 → 걸어서 퇴장

    // **뒤에 붙일 것** — `NpcData.NpcType`이 정수로 직렬화된다. 중간에 끼우면 이미 저작한
    // 역할 에셋이 통째로 밀린다(`StatName`·`JobCategory`와 같은 규칙).

    // 떠돌이: 걸어서 등장 → **머무는 동안 배회** → 걸어서 퇴장.
    //
    // 주민과 갈리는 것은 **떠난다**는 것 하나다. 주민은 제 마을에 눌러살지만 떠돌이는 지나간다 —
    // 그래서 만나는 것이 **기회**가 된다(지금 말을 안 걸면 간다). 눌러살게 두면 지도에 떠돌이가
    // 쌓이고, 쌓이면 아무도 사건이 아니게 된다.
    Drifter,
}
