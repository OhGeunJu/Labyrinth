using System;

// **켰다 껐다 하는 모드는 한 번에 하나다 — 그 규칙이 사는 자리**(2026-09-02).
//
// 건설 · 채굴 · 운반 · 구역은 전부 **드래그의 뜻을 바꾸는 상태**다. 둘이 같이 켜지면 같은
// 드래그가 무엇을 하는지가 **누가 먼저 입력을 먹느냐**로 정해지고, 그건 화면에 안 적혀 있다.
//
// 그래서 켤 때 서로 꺼야 하는데, **각 모드가 나머지 셋을 직접 끄게 하면 안 된다** — 모드가
// 하나 늘 때마다 이미 있는 것들을 전부 고쳐야 하고, 하나만 빠뜨려도 *"저 둘만 같이 켜진다"*가
// 생긴다. 넷이면 열두 줄이다.
//
// **그래서 아는 것을 뒤집는다**: 켜는 쪽은 *"내가 켰다"*만 알리고, 나머지는 *"내가 아니면
// 끈다"*만 안다. 모드는 자기 자신만 알면 되고, 새 모드는 두 줄로 끼어든다.
public static class ExclusiveMode
{
    // 누가 켰나. **`object`로 든다** — 여기가 모드의 타입을 알면 새 모드를 더할 때마다
    // 이 파일도 같이 고쳐야 한다(그러면 한 곳에 모은 뜻이 없다).
    public static event Action<object> Claimed;

    public static void Claim(object owner) => Claimed?.Invoke(owner);
}
